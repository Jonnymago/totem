type Listener = (lang: SupportedLanguage) => void;
const listeners = new Set<Listener>();

let defaultLang: SupportedLanguage = 'it';
let sessionLang: SupportedLanguage | null = null;
let currentLang: SupportedLanguage = 'it';

function isSupportedLanguage(value: unknown): value is SupportedLanguage {
  return typeof value === 'string' && (['it', 'en', 'es', 'fr', 'de'] as string[]).includes(value);
}

// Load initial saved kiosk language from localStorage
try {
  const saved = localStorage.getItem('totem_app_language');
  if (saved && isSupportedLanguage(saved)) {
    defaultLang = saved;
    currentLang = saved;
  }
} catch {}

function notify() {
  listeners.forEach((fn) => {
    try {
      fn(currentLang);
    } catch (e) {
      console.warn('i18n listener error:', e);
    }
  });
}

export function getCurrentLanguage(): SupportedLanguage {
  return currentLang;
}

export function isCustomerSessionActive(): boolean {
  return sessionLang !== null;
}

/** Set default kiosk language permanently in localStorage */
export function setLanguage(lang: SupportedLanguage) {
  if (!isSupportedLanguage(lang)) return;
  defaultLang = lang;
  sessionLang = null;
  currentLang = lang;
  try {
    localStorage.setItem('totem_app_language', lang);
  } catch {}
  notify();
}

/** Momentary customer session language (does NOT overwrite kiosk default) */
export function setCustomerSessionLanguage(lang: SupportedLanguage) {
  if (!isSupportedLanguage(lang)) return;
  sessionLang = lang;
  currentLang = lang;
  notify();
}

/** Reset customer session language back to kiosk default */
export function resetCustomerSessionLanguage() {
  if (sessionLang === null) return;
  sessionLang = null;
  currentLang = defaultLang;
  notify();
}

export function t(key: string, defaultText?: string): string {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.it;
  if (dict[key]) return dict[key];
  const fallback = TRANSLATIONS.it[key];
  if (fallback) return fallback;
  return defaultText || key;
}

export function useI18n() {
  const [lang, setLangState] = useState<SupportedLanguage>(currentLang);

  useEffect(() => {
    const listener: Listener = (newLang) => {
      setLangState(newLang);
    };
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  const translate = (key: string, defaultText?: string) => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.it;
    if (dict[key]) return dict[key];
    const fallback = TRANSLATIONS.it[key];
    if (fallback) return fallback;
    return defaultText || key;
  };

  return {
    lang,
    defaultLang,
    isCustomerSession: sessionLang !== null,
    setLanguage,
    setCustomerSessionLanguage,
    resetCustomerSessionLanguage,
    t: translate,
    languages: SUPPORTED_LANGUAGES,
  };
}
